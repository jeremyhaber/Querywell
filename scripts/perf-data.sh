#!/usr/bin/env bash
# Creates (once, idempotently) a 1,000,000-row WordPress-like table `big_posts` in schema `qw_perf`
# on the Docker MySQL 8.4 and Postgres 16 servers. Generated server-side; never dropped by tests.
# usage: scripts/perf-data.sh [mysql|postgres|mariadb ...]   (default: mysql postgres)
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
TARGETS=("$@"); [ ${#TARGETS[@]} -gt 0 ] || TARGETS=(mysql postgres)

mysql_like() { # service
  local svc="$1" cli=mysql
  [ "$svc" = mariadb11 ] && cli=mariadb
  local run=(docker compose exec -T "$svc" "$cli" -uroot -proot_pw --batch --skip-column-names)
  local have
  have="$("${run[@]}" -e "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='qw_perf' AND table_name='big_posts'" 2>/dev/null || echo 0)"
  if [ "$have" = "1" ]; then
    local n; n="$("${run[@]}" -e "SELECT COUNT(*) FROM qw_perf.big_posts")"
    if [ "$n" = "1000000" ]; then echo "$svc: qw_perf.big_posts already has 1,000,000 rows"; return; fi
    "${run[@]}" -e "DROP TABLE qw_perf.big_posts"
  fi
  echo "$svc: generating 1,000,000 rows…"
  "${run[@]}" <<'SQL'
CREATE DATABASE IF NOT EXISTS qw_perf DEFAULT CHARACTER SET utf8mb4;
GRANT ALL ON qw_perf.* TO 'querywell'@'%';
CREATE TABLE qw_perf.big_posts (
  ID bigint unsigned NOT NULL AUTO_INCREMENT,
  post_author bigint unsigned NOT NULL DEFAULT 0,
  post_title varchar(255) NOT NULL DEFAULT '',
  post_content text NOT NULL,
  post_date datetime NOT NULL,
  post_status enum('publish','draft','pending','private','trash') NOT NULL DEFAULT 'publish',
  post_type varchar(20) NOT NULL DEFAULT 'post',
  post_name varchar(200) NOT NULL DEFAULT '',
  menu_order int NOT NULL DEFAULT 0,
  PRIMARY KEY (ID),
  KEY post_author (post_author),
  KEY type_status_date (post_type, post_status, post_date, ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
SET SESSION cte_max_recursion_depth = 2000000;
INSERT INTO qw_perf.big_posts (ID, post_author, post_title, post_content, post_date, post_status, post_type, post_name, menu_order)
WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 1000000)
SELECT i, i % 500, CONCAT('Post title number ', i), REPEAT(CONCAT('Lorem ipsum dolor sit amet ', i, '. '), 18),
       TIMESTAMP('2015-01-01') + INTERVAL i * 3500 SECOND,
       ELT(1 + i % 5, 'publish','publish','draft','pending','trash'), IF(i % 7 = 0, 'page', 'post'),
       CONCAT('post-', i), i % 20
FROM n;
ANALYZE TABLE qw_perf.big_posts;
SQL
  "${run[@]}" -e "SELECT COUNT(*) FROM qw_perf.big_posts"
}

postgres_perf() {
  local run=(docker compose exec -T postgres16 psql -U querywell -d querywell_test -v ON_ERROR_STOP=1 -At)
  local have
  have="$("${run[@]}" -c "SELECT to_regclass('qw_perf.big_posts') IS NOT NULL AND (SELECT count(*) FROM qw_perf.big_posts)=1000000" 2>/dev/null || echo f)"
  if [ "$have" = "t" ]; then echo "postgres16: qw_perf.big_posts already has 1,000,000 rows"; return; fi
  echo "postgres16: generating 1,000,000 rows…"
  "${run[@]}" <<'SQL'
CREATE SCHEMA IF NOT EXISTS qw_perf;
DROP TABLE IF EXISTS qw_perf.big_posts;
CREATE TABLE qw_perf.big_posts (
  "ID" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_author bigint NOT NULL DEFAULT 0,
  post_title varchar(255) NOT NULL DEFAULT '',
  post_content text NOT NULL,
  post_date timestamp NOT NULL,
  post_status varchar(20) NOT NULL DEFAULT 'publish',
  post_type varchar(20) NOT NULL DEFAULT 'post',
  post_name varchar(200) NOT NULL DEFAULT '',
  menu_order int NOT NULL DEFAULT 0
);
INSERT INTO qw_perf.big_posts (post_author, post_title, post_content, post_date, post_status, post_type, post_name, menu_order)
SELECT i % 500, 'Post title number ' || i, repeat('Lorem ipsum dolor sit amet ' || i || '. ', 18),
       timestamp '2015-01-01' + (i::bigint * 3500) * interval '1 second',
       (ARRAY['publish','publish','draft','pending','trash'])[1 + i % 5], CASE WHEN i % 7 = 0 THEN 'page' ELSE 'post' END,
       'post-' || i, i % 20
FROM generate_series(1, 1000000) AS i;
CREATE INDEX big_posts_author ON qw_perf.big_posts (post_author);
CREATE INDEX big_posts_type_status_date ON qw_perf.big_posts (post_type, post_status, post_date, "ID");
ANALYZE qw_perf.big_posts;
SELECT count(*) FROM qw_perf.big_posts;
SQL
}

for t in "${TARGETS[@]}"; do
  case "$t" in
    mysql) mysql_like mysql8 ;;
    mariadb) mysql_like mariadb11 ;;
    postgres) postgres_perf ;;
    *) echo "unknown target $t" >&2; exit 2 ;;
  esac
done
